    cal_records: list[dict[str, Any]] = []
    for _ in range(60):
        d_um = float(rng_cal.uniform(3.0, 26.0))
        u_m_s = float(rng_cal.uniform(0.18, 0.36))
        sigma_b = float(rng_cal.uniform(0.003, 0.008))
        dt_k = float(rng_cal.uniform(-2.0, 5.0))
        obs_lo = world.generate_mismatched_observables(
            d_um, u_m_s, sigma_b, dt_k,
            axial_taper_slope=0.06, bruggeman_porosity=0.12, caco3_biofilm_mix_frac=0.15,
            aging_days=5.0, c_par_uncalibrated_offset_pf=c_par_offset_pf,
            f_th_hz=4.0, f_elec_hz=5000.0, rng=rng_cal
        )
        obs_hi = world.generate_mismatched_observables(
            d_um, u_m_s, sigma_b, dt_k,
            axial_taper_slope=0.06, bruggeman_porosity=0.12, caco3_biofilm_mix_frac=0.15,
            aging_days=5.0, c_par_uncalibrated_offset_pf=c_par_offset_pf,
            f_th_hz=36.0, f_elec_hz=50000.0, rng=rng_cal
        )
        dp_pa = 1200.0 * (u_m_s / 0.25) * (1.0 / max(1.0 - (d_um / 1000.0), 0.2)) ** 3
        cal_records.append({
            "true_df_um": d_um,
            "obs_lo": obs_lo,
            "obs_hi": obs_hi,
            "flow_meas_m_s": u_m_s,
            "ec_bulk_s_m": sigma_b,
            "dp_pa": dp_pa,
        })

    baselines = CalibratedConventionalBaselines()
    frozen_baseline_hash = baselines.fit_and_freeze(cal_records, cal_lo, cal_hi)

    frozen_config = {
        "schema": "openline.otdb_apw.release_004.frozen_benchmark_contract.v1",
        "calibration_samples": 60,
        "calibration_seed": 20260401,
        "holdout_seed": 20261115,
        "frozen_baseline_weights_sha256": frozen_baseline_hash,
        "epistemic_label": "SYNTHETIC_LITERATURE_INSPIRED_COMPUTATIONAL_TRIALS_ONLY",
        "raw_beamline_files_ingested": 0,
        "wafers_fabricated": 0,
        "wet_lab_hours": 0,
    }
    frozen_config_sha256 = hashlib.sha256(
        json.dumps(frozen_config, sort_keys=True).encode("utf-8")
    ).hexdigest()

    rng = np.random.default_rng(20261115)

    # =========================================================================
    # Scenario S1: Khaja-2026-Inspired Constant-EC Colloidal/Particulate Fouling
    # (No soluble concentration polarization: CP = 1.00x, steady laminar flow)
    # =========================================================================
    s1_otdb_err, s1_b1_err, s1_b2_err, s1_b3_err = [], [], [], []
    for _ in range(40):
        d_um = float(rng.uniform(4.0, 24.0))
        u_m_s = float(rng.uniform(0.20, 0.34))
        sigma_b = float(rng.uniform(0.004, 0.007))
        dt_k = float(rng.uniform(-1.5, 4.0))
        obs_lo = world.generate_mismatched_observables(
            d_um, u_m_s, sigma_b, dt_k,
            axial_taper_slope=0.05, bruggeman_porosity=0.12, caco3_biofilm_mix_frac=0.15,
            aging_days=5.0, c_par_uncalibrated_offset_pf=c_par_offset_pf,
            f_th_hz=4.0, f_elec_hz=5000.0, rng=rng
        )
        obs_hi = world.generate_mismatched_observables(
            d_um, u_m_s, sigma_b, dt_k,
            axial_taper_slope=0.05, bruggeman_porosity=0.12, caco3_biofilm_mix_frac=0.15,
            aging_days=5.0, c_par_uncalibrated_offset_pf=c_par_offset_pf,
            f_th_hz=36.0, f_elec_hz=50000.0, rng=rng
        )
