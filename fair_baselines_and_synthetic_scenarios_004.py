        est_otdb = otdb_est.estimate(obs_lo, obs_hi, mode="OTDB_APW_REV_B_CALIBRATED", clean_cal_offset_im_lo_us=cal_lo, clean_cal_offset_im_hi_us=cal_hi)
        preds = baselines.predict(obs_lo, obs_hi, cal_lo, cal_hi, u_m_s, sigma_b, dp_pa)

        s1_otdb_err.append(abs(est_otdb["estimated_fouling_um"] - d_um) / d_um * 100.0)
        s1_b1_err.append(abs(preds["b1_eis_drt_um"] - d_um) / d_um * 100.0)
